/**
 * Claude WP Bridge — Admin JavaScript
 *
 * Handles API key generation, revocation, clipboard copy,
 * and audit log management via AJAX.
 *
 * @package ClaudeWPBridge
 * @since   1.0.0
 */

/* global jQuery, cwpb */
(function ($) {
	'use strict';

	/**
	 * Copy text to the clipboard.
	 *
	 * @param {string} text    The text to copy.
	 * @param {string} message Optional alert message (defaults to key_copied).
	 */
	function copyToClipboard(text, message) {
		var msg = message || cwpb.strings.key_copied;
		if (navigator.clipboard && navigator.clipboard.writeText) {
			navigator.clipboard.writeText(text).then(function () {
				alert(msg);
			});
		} else {
			// Fallback for older browsers.
			var $temp = $('<textarea>');
			$('body').append($temp);
			$temp.val(text).select();
			document.execCommand('copy');
			$temp.remove();
			alert(msg);
		}
	}

	// Generate API Key.
	$(document).on('click', '#cwpb-generate-key, #cwpb-regenerate-key', function (e) {
		e.preventDefault();

		var isRegenerate = $(this).attr('id') === 'cwpb-regenerate-key';
		if (isRegenerate && !confirm(cwpb.strings.confirm_generate)) {
			return;
		}

		var $button = $(this);
		$button.prop('disabled', true).text('Generating...');

		$.post(cwpb.ajax_url, {
			action: 'cwpb_generate_key',
			nonce: cwpb.nonce
		}, function (response) {
			if (response.success) {
				// Reload so the persistent key display shows the new key.
				location.reload();
			} else {
				alert('Error: ' + (response.data || 'Unknown error'));
				$button.prop('disabled', false).text(isRegenerate ? 'Regenerate Key' : 'Generate API Key');
			}
		}).fail(function () {
			alert('Request failed. Please try again.');
			$button.prop('disabled', false).text(isRegenerate ? 'Regenerate Key' : 'Generate API Key');
		});
	});

	// Revoke API Key.
	$(document).on('click', '#cwpb-revoke-key', function (e) {
		e.preventDefault();

		if (!confirm(cwpb.strings.confirm_revoke)) {
			return;
		}

		var $button = $(this);
		$button.prop('disabled', true);

		$.post(cwpb.ajax_url, {
			action: 'cwpb_revoke_key',
			nonce: cwpb.nonce
		}, function (response) {
			if (response.success) {
				location.reload();
			} else {
				alert('Error: ' + (response.data || 'Unknown error'));
				$button.prop('disabled', false);
			}
		});
	});

	// Copy API Key.
	$(document).on('click', '#cwpb-copy-key', function (e) {
		e.preventDefault();
		var key = $('#cwpb-new-key').text();
		copyToClipboard(key);
	});

	// Copy to AI — fetch the guide from server (generated by PHP for accuracy).
	$(document).on('click', '#cwpb-copy-ai', function (e) {
		e.preventDefault();
		var key = $('#cwpb-new-key').text().trim();
		if (!key) {
			return;
		}

		var $button = $(this);
		$button.prop('disabled', true).text('Loading...');

		$.post(cwpb.ajax_url, {
			action: 'cwpb_get_ai_guide',
			nonce: cwpb.nonce
		}, function (response) {
			$button.prop('disabled', false).text('Copy to AI');

			if (response.success) {
				var $container = $('#cwpb-ai-text-container');
				var $textarea  = $('#cwpb-ai-textarea');
				$textarea.val(response.data.guide);
				$container.slideDown(200, function () {
					$textarea.focus().select();
				});
			} else {
				alert('Error: ' + (response.data || 'Could not generate AI guide.'));
			}
		}).fail(function () {
			$button.prop('disabled', false).text('Copy to AI');
			alert('Request failed. Please try again.');
		});
	});

	// Select All in AI textarea.
	$(document).on('click', '#cwpb-select-all-ai', function (e) {
		e.preventDefault();
		var $textarea = $('#cwpb-ai-textarea');
		$textarea.focus().select();
	});

	// Hide AI textarea.
	$(document).on('click', '#cwpb-hide-ai-text', function (e) {
		e.preventDefault();
		$('#cwpb-ai-text-container').slideUp(200);
	});

	// Clear Audit Logs.
	$(document).on('click', '#cwpb-clear-logs', function (e) {
		e.preventDefault();

		if (!confirm(cwpb.strings.confirm_clear)) {
			return;
		}

		var $button = $(this);
		$button.prop('disabled', true);

		$.post(cwpb.ajax_url, {
			action: 'cwpb_clear_logs',
			nonce: cwpb.nonce
		}, function (response) {
			if (response.success) {
				location.reload();
			} else {
				alert('Error: ' + (response.data || 'Unknown error'));
				$button.prop('disabled', false);
			}
		});
	});

})(jQuery);
